"""Cut the profile avatar presets from the DAIRI character packages.

Usage (from launcher/, needs ImageMagick 7):
  python3 scripts/make-dairi-avatars.py PACKAGES_DIR

PACKAGES_DIR holds the original character ZIPs named in docs/dairi-art/selection.json.
Every expression in a character's own 通常 (normal) and 赤面 (blush) folders shares
the bundled portrait's pose, so one face crop from docs/dairi-art/avatar-crops.json
serves them all. Props, companion dolls and alternate costumes are skipped.

Writes 256px WebP crops to public/assets/dairi/avatars/<character>/<expression>.webp,
the typed catalog app/models/profile-avatar-catalog.ts, and the published file list
between the "dairi avatars" markers in lib/frontend-static-manifest.mjs. The packages
themselves are never copied.
"""
import json
import re
import shutil
import subprocess
import sys
import tempfile
import zipfile
from pathlib import Path

LAUNCHER = Path(__file__).resolve().parent.parent
DOCS = LAUNCHER.parent / "docs/dairi-art"
OUTPUT = LAUNCHER / "public/assets/dairi/avatars"
CATALOG = LAUNCHER / "app/models/profile-avatar-catalog.ts"
MANIFEST = LAUNCHER / "lib/frontend-static-manifest.mjs"
PAD = 400  # Crops may run past the canvas edge; transparent padding keeps them square.

# Package expression names -> stable ids, in display order. Variant spellings share an id.
EXPRESSIONS = {
    "微笑": "smile", "余裕": "confident", "余裕影": "confident-shade", "普通": "neutral", "笑い": "laugh",
    "苦笑": "wry-smile", "苦笑影": "wry-smile-shade", "ドヤ": "smug", "不敵": "fearless", "強気": "bold",
    "イイネ！": "nice", "そうこなくっちゃ": "eager", "ワクワクするぜ～": "excited", "マジだよ": "for-real",
    "ふむ": "musing", "回答": "explaining", "驚く": "surprised", "驚き": "surprised", "焦り": "flustered",
    "慌て": "flustered", "緊張": "nervous", "迫真": "intense", "困り": "troubled", "困る": "troubled",
    "弱る": "dismayed", "弱る影": "dismayed-shade", "・・・・": "speechless", "これだから…": "sigh",
    "ったく今の若いもんは": "grumble", "不満": "pout", "不機嫌": "sulky", "呆れ": "exasperated",
    "呆れ影": "exasperated-shade", "怒る": "angry", "怒り": "angry", "怒り影": "angry-shade", "睨む": "glare",
    "睨む影": "glare-shade", "剣呑": "menacing", "狂気": "mad", "狂気影": "mad-shade", "泣く": "cry",
}
ORDER = list(dict.fromkeys(EXPRESSIONS.values()))
GROUPS = {"通常": "", "赤面": "blush-"}


def member_name(info):
    name = info.filename
    if not info.flag_bits & 0x800:
        try:
            name = name.encode("cp437").decode("cp932")
        except (UnicodeEncodeError, UnicodeDecodeError):
            pass
    return name


def expressions(archive, bundled):
    """(id, member) pairs from the bundled portrait's costume folder, default first."""
    costume = bundled.rsplit("/", 2)[0]
    found = {}
    for info in archive.infolist():
        name = member_name(info)
        match = re.fullmatch(re.escape(costume) + r"/(通常|赤面)/[^/]*（(.+)）\.png", name)
        if not match or match.group(2) not in EXPRESSIONS:
            continue
        found.setdefault(GROUPS[match.group(1)] + EXPRESSIONS[match.group(2)], info)
    rank = lambda key: (key.startswith("blush-"), ORDER.index(key.removeprefix("blush-")))
    default = next(key for key, info in found.items() if member_name(info) == bundled)
    return [(key, found[key]) for key in sorted(found, key=lambda key: (key != default, rank(key)))]


def main(packages):
    crops = json.loads((DOCS / "avatar-crops.json").read_text())["crops"]
    selection = {entry["id"]: entry for entry in json.loads((DOCS / "selection.json").read_text())}
    shutil.rmtree(OUTPUT, ignore_errors=True)
    catalog, files = {}, []
    with tempfile.TemporaryDirectory() as work:
        for character, (cx, cy, side) in crops.items():
            entry = selection[character]
            (OUTPUT / character).mkdir(parents=True)
            x, y = round(cx - side / 2) + PAD, round(cy - side / 2) + PAD
            with zipfile.ZipFile(Path(packages) / entry["archive"]) as archive:
                chosen = expressions(archive, entry["member"])
                for key, info in chosen:
                    source = Path(work) / "source.png"
                    source.write_bytes(archive.read(info))
                    target = OUTPUT / character / f"{key}.webp"
                    subprocess.run(["magick", source, "-bordercolor", "none", "-border", str(PAD),
                                    "-crop", f"{side}x{side}+{x}+{y}", "+repage", "-resize", "256x256",
                                    "-define", "webp:alpha-quality=90", "-quality", "82", target], check=True)
                    files.append(target.relative_to(LAUNCHER / "public").as_posix())
            catalog[character] = [key for key, _ in chosen]
    body = ",\n".join(f"  {character}: {json.dumps(keys)}" for character, keys in catalog.items())
    CATALOG.write_text(
        "// Generated by scripts/make-dairi-avatars.py; do not edit.\n"
        "/** Expression ids per character, the bundled portrait's first. */\n"
        f"export const AVATAR_CATALOG = {{\n{body},\n}} as const;\n")
    manifest = MANIFEST.read_text()
    begin = "  // BEGIN dairi avatars: generated by scripts/make-dairi-avatars.py\n"
    end = "  // END dairi avatars\n"
    head, rest = manifest.split(begin)
    _, tail = rest.split(end)
    MANIFEST.write_text(head + begin + "".join(f"  ['{file}', false],\n" for file in files) + end + tail)
    print(f"{len(files)} avatars for {len(catalog)} characters")


if __name__ == "__main__":
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    main(sys.argv[1])
